"""The shapes kernel (issue 39, phase 2, design §8.2): the payloads of the bridge, written once as `TypedDict`s, and
everything generated from them: JSON Schemas, the window's TypeScript types, and a checker for a real value.

A shape is a `TypedDict` whose every field is `Annotated[T, F(doc, shown=...)]` (`NotRequired[...]` for a key that may be
absent), registered with `@shape`. A named type that several shapes share (a `Literal` of words, a tuple, a union of
shapes) is registered with `alias(name, tp)`, which returns `tp` tagged with its name, so the generated code names it
(`export type Quality = ...`, `$defs/Quality`) instead of copying it into every field.

The closed set of constructs (anything else is a `ShapeError` at import, naming the class and the field): `str`,
`int`, `float`, `bool`, `Literal[...]` of str / int / bool values, `X | None`, `NotRequired[X]`, `list[X]`,
`dict[str, X]`, a registered `TypedDict`, a `TypedDict` that subclasses registered ones, a registered alias, a union
`X | Y` of registered `TypedDict`s, a fixed `tuple[A, B, ...]`, and `typing.Any` (which the field's doc must explain).

No dependency: the JSON Schema and the checker are written here, from one reading of the types.
A `Registry` holds one set of shapes; the module-level `SHAPES`, `ALIASES`, `shape`, `alias`, `json_schema`,
`typescript` and `validate` are the one registry of the product. Tests make their own."""
from __future__ import annotations

import textwrap
import types
import typing
from dataclasses import dataclass
from typing import Annotated, Any, Literal, NotRequired, Required, Union

SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"
HEADER = "// Generated by python -m discjockey.hub.shapes --export from discjockey/hub/shapes/. Do not edit."
PRIMITIVES = {str: "string", int: "integer", float: "number", bool: "boolean"}
TS_PRIMITIVES = {str: "string", int: "number", float: "number", bool: "boolean"}
NoneType = type(None)


class ShapeError(TypeError):
    """A shape or alias that is not in the closed set; raised at import, naming the class and the field."""


@dataclass(frozen=True)
class F:
    """What a field is. `doc` is its meaning for the reference. `shown` is whether the window shows it: False for ids,
    `rev`, keys the window sends back, URLs and raw numbers that have a `_text` companion. It is reference metadata
    (`x-shown` in the JSON Schema), nothing checks it."""
    doc: str
    shown: bool = True


@dataclass(frozen=True)
class _Name:
    """The tag `alias` puts on the type it returns: the name of the alias, found again in the type hints."""
    name: str


# --- the parsed form (one reading of the types; the JSON Schema, the TypeScript and the checker all walk it) ---

@dataclass(frozen=True)
class Prim:
    py: type


@dataclass(frozen=True)
class Lit:
    values: tuple


@dataclass(frozen=True)
class Opt:
    inner: Any


@dataclass(frozen=True)
class Many:
    inner: Any


@dataclass(frozen=True)
class Keyed:
    inner: Any


@dataclass(frozen=True)
class Tup:
    items: tuple


@dataclass(frozen=True)
class AnyType:
    pass


@dataclass(frozen=True)
class Ref:
    name: str


@dataclass(frozen=True)
class Either:
    """A union of registered shapes (names)."""
    names: tuple


@dataclass(frozen=True)
class Field:
    name: str
    node: Any
    required: bool
    doc: str
    shown: bool


@dataclass(frozen=True)
class Spec:
    """One shape as the kernel keeps it: all its fields (inherited ones first), the registered shapes it extends and the
    fields it adds itself."""
    cls: type
    doc: str
    fields: tuple
    bases: tuple
    own: tuple


@dataclass(frozen=True)
class AliasSpec:
    name: str
    node: Any
    doc: str
    const: str | None


def _peel(tp) -> tuple[Any, list, bool | None]:
    """Strip `Annotated` and `NotRequired` / `Required` wrappers in any nesting: the bare type, every piece of
    annotation metadata in order, and whether a wrapper said the key is required (True), not required (False) or
    nothing (None)."""
    metas: list = []
    required: bool | None = None
    while True:
        origin = typing.get_origin(tp)
        if origin is Annotated:
            tp, *more = typing.get_args(tp)
            metas.extend(more)
        elif origin is NotRequired:
            tp, required = typing.get_args(tp)[0], False
        elif origin is Required:
            tp, required = typing.get_args(tp)[0], True
        else:
            return tp, metas, required


def _is_union(tp) -> bool:
    return typing.get_origin(tp) in (Union, types.UnionType)


def _quote(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _words(text: str) -> str:
    return " ".join(text.split())


class Registry:
    """One set of shapes and aliases, in registration order."""

    def __init__(self) -> None:
        self.shapes: dict[str, type] = {}
        self.aliases: dict[str, AliasSpec] = {}
        self._specs: dict[str, Spec] = {}
        self._order: list[str] = []

    # --- registering ---

    def shape(self, cls: type) -> type:
        """Class decorator: register a `TypedDict` and check it at once."""
        name = cls.__name__
        if not typing.is_typeddict(cls):
            raise ShapeError(f"{name}: a shape is a TypedDict")
        self._free(name)
        bases = []
        for base in getattr(cls, "__orig_bases__", ()):
            if base is typing.TypedDict:
                continue
            if not typing.is_typeddict(base) or self.shapes.get(base.__name__) is not base:
                raise ShapeError(f"{name}: its base {getattr(base, '__name__', base)!r} is not a registered shape")
            bases.append(base.__name__)
        hints = typing.get_type_hints(cls, include_extras=True)
        inherited = {f.name for b in bases for f in self._specs[b].fields}
        fields = []
        for key, hint in hints.items():
            fields.append(self._field(name, key, hint, total=getattr(cls, "__total__", True)))
        spec = Spec(cls=cls, doc=_words(cls.__doc__ or ""), fields=tuple(fields), bases=tuple(bases),
                    own=tuple(f for f in fields if f.name not in inherited))
        self.shapes[name] = cls
        self._specs[name] = spec
        self._order.append(name)
        return cls

    def alias(self, name: str, tp, *, const: str | None = None, doc: str = ""):
        """Register a named type; returns `tp` tagged with the name, to be used as a type. `const` (a `Literal` alias)
        also makes TypeScript's `export const <const>: readonly <name>[] = [...]`."""
        self._free(name)
        node = self._node(tp, f"alias {name}")
        if const is not None and not isinstance(node, Lit):
            raise ShapeError(f"alias {name}: `const` needs a Literal")
        self.aliases[name] = AliasSpec(name, node, _words(doc), const)
        self._order.append(name)
        return Annotated[tp, _Name(name)]

    def _free(self, name: str) -> None:
        if name in self.shapes or name in self.aliases:
            raise ShapeError(f"{name}: registered twice")

    # --- reading the types ---

    def _field(self, owner: str, key: str, hint, *, total: bool) -> Field:
        where = f"{owner}.{key}"
        tp, metas, required = _peel(hint)
        marks = [m for m in metas if isinstance(m, F)]
        if len(marks) != 1:
            raise ShapeError(f"{where}: needs exactly one F(doc, shown), has {len(marks)}")
        node = self._node(hint, where)
        return Field(key, node, total if required is None else required, marks[0].doc, marks[0].shown)

    def _node(self, tp, where: str):
        tp, metas, _ = _peel(tp)
        for tag in metas:
            if isinstance(tag, _Name):
                if tag.name not in self.aliases:
                    raise ShapeError(f"{where}: alias {tag.name!r} is not registered here")
                return Ref(tag.name)
        if tp is Any:
            return AnyType()
        if tp in PRIMITIVES:
            return Prim(tp)
        origin = typing.get_origin(tp)
        args = typing.get_args(tp)
        if origin is Literal:
            for value in args:
                if not isinstance(value, (str, int, bool)):
                    raise ShapeError(f"{where}: Literal holds {value!r}; only str, int and bool values")
            return Lit(args)
        if _is_union(tp):
            rest = [a for a in args if a is not NoneType]
            if not rest:
                raise ShapeError(f"{where}: None alone is no type")
            inner = self._node(rest[0], where) if len(rest) == 1 else self._either(rest, where)
            return Opt(inner) if len(rest) != len(args) else inner
        if origin is list:
            return Many(self._node(args[0], where)) if args else self._refuse(tp, where)
        if origin is dict:
            if len(args) != 2 or args[0] is not str:
                raise ShapeError(f"{where}: a dict needs str keys, dict[str, X] (got {tp})")
            return Keyed(self._node(args[1], where))
        if origin is tuple:
            if not args or args[-1] is Ellipsis or args == ((),):
                raise ShapeError(f"{where}: a tuple is fixed, tuple[A, B, ...] (got {tp})")
            return Tup(tuple(self._node(a, where) for a in args))
        if isinstance(tp, type) and typing.is_typeddict(tp):
            if self.shapes.get(tp.__name__) is not tp:
                raise ShapeError(f"{where}: {tp.__name__} is not a registered shape")
            return Ref(tp.__name__)
        return self._refuse(tp, where)

    def _either(self, members: list, where: str) -> Either:
        names = []
        for member in members:
            if not (isinstance(member, type) and typing.is_typeddict(member) and self.shapes.get(member.__name__) is member):
                raise ShapeError(f"{where}: a union holds registered shapes only (got {member})")
            names.append(member.__name__)
        return Either(tuple(names))

    @staticmethod
    def _refuse(tp, where: str):
        raise ShapeError(f"{where}: {tp!r} is not in the closed set of shape types")

    def values(self, name: str) -> tuple:
        """The words of a `Literal` alias, in the order they were written."""
        node = self.aliases[name].node if name in self.aliases else None
        if not isinstance(node, Lit):
            raise KeyError(f"{name} is no alias of a Literal")
        return node.values

    # --- JSON Schema ---

    def _schema(self, node) -> dict:
        if isinstance(node, Prim):
            return {"type": PRIMITIVES[node.py]}
        if isinstance(node, Lit):
            return {"const": node.values[0]} if len(node.values) == 1 else {"enum": list(node.values)}
        if isinstance(node, Opt):
            return {"anyOf": [self._schema(node.inner), {"type": "null"}]}
        if isinstance(node, Many):
            return {"type": "array", "items": self._schema(node.inner)}
        if isinstance(node, Keyed):
            return {"type": "object", "additionalProperties": self._schema(node.inner)}
        if isinstance(node, Tup):
            n = len(node.items)
            return {"type": "array", "prefixItems": [self._schema(i) for i in node.items], "items": False,
                    "minItems": n, "maxItems": n}
        if isinstance(node, AnyType):
            return {}
        if isinstance(node, Ref):
            return {"$ref": f"#/$defs/{node.name}"}
        return {"anyOf": [{"$ref": f"#/$defs/{n}"} for n in node.names]}

    def definition(self, name: str) -> dict:
        """The JSON Schema of one shape or alias, its references as `#/$defs/<name>`."""
        if name in self.aliases:
            alias = self.aliases[name]
            out = self._schema(alias.node)
            return {**out, "description": alias.doc} if alias.doc else out
        spec = self._known(name)
        props = {f.name: {**self._schema(f.node), "description": f.doc, "x-shown": f.shown} for f in spec.fields}
        out: dict = {"type": "object", "properties": props}
        required = [f.name for f in spec.fields if f.required]
        if required:
            out["required"] = required
        out["additionalProperties"] = False
        return {**out, "description": spec.doc} if spec.doc else out

    def _known(self, name: str) -> Spec:
        if name not in self._specs:
            raise KeyError(f"no shape called {name}")
        return self._specs[name]

    def _uses(self, node) -> list[str]:
        if isinstance(node, Ref):
            return [node.name]
        if isinstance(node, Either):
            return list(node.names)
        if isinstance(node, (Opt, Many, Keyed)):
            return self._uses(node.inner)
        if isinstance(node, Tup):
            return [n for i in node.items for n in self._uses(i)]
        return []

    def _needs(self, name: str) -> list[str]:
        if name in self.aliases:
            return self._uses(self.aliases[name].node)
        spec = self._known(name)
        return list(spec.bases) + [n for f in spec.fields for n in self._uses(f.node)]

    def definitions(self, names: list[str] | None = None) -> dict[str, dict]:
        """The schemas of `names` and everything they use (all of them when None), in registration order."""
        if names is None:
            wanted = set(self._order)
        else:
            wanted, todo = set(), list(names)
            while todo:
                name = todo.pop()
                if name not in wanted:
                    wanted.add(name)
                    todo.extend(self._needs(name))
        return {n: self.definition(n) for n in self._order if n in wanted}

    def json_schema(self, name: str) -> dict:
        """The JSON Schema (draft 2020-12) of one shape or alias, with the definitions it uses."""
        if name not in self.aliases:
            self._known(name)
        return {"$schema": SCHEMA_DIALECT, "$ref": f"#/$defs/{name}", "$defs": self.definitions([name])}

    # --- TypeScript ---

    def _ts(self, node) -> tuple[str, bool]:
        """The TypeScript of a node, and whether it is a union (an array of it needs brackets)."""
        if isinstance(node, Prim):
            return TS_PRIMITIVES[node.py], False
        if isinstance(node, Lit):
            parts = [_ts_value(v) for v in node.values]
            return " | ".join(parts), len(parts) > 1
        if isinstance(node, Opt):
            inner, _ = self._ts(node.inner)
            return f"{inner} | null", True
        if isinstance(node, Many):
            inner, union = self._ts(node.inner)
            return (f"({inner})[]" if union else f"{inner}[]"), False
        if isinstance(node, Keyed):
            inner, _ = self._ts(node.inner)
            return f"Record<string, {inner}>", False
        if isinstance(node, Tup):
            return "[" + ", ".join(self._ts(i)[0] for i in node.items) + "]", False
        if isinstance(node, AnyType):
            return "any", False
        if isinstance(node, Ref):
            return node.name, False
        return " | ".join(node.names), True

    def typescript(self) -> str:
        """The whole generated TypeScript file, in registration order."""
        out = [HEADER, ""]
        for name in self._order:
            if name in self.aliases:
                out.extend(self._ts_alias(self.aliases[name]))
            else:
                out.extend(self._ts_shape(name, self._specs[name]))
        return "\n".join(out) + "\n"

    def _ts_alias(self, alias: AliasSpec) -> list[str]:
        lines = _ts_comment(alias.doc, "")
        text, _ = self._ts(alias.node)
        one = f"export type {alias.name} = {text};"
        if len(one) <= 110 or not isinstance(alias.node, Lit):
            lines.append(one)
        else:
            lines.append(f"export type {alias.name} =")
            lines.extend(f"  | {_ts_value(v)}" for v in alias.node.values)
            lines[-1] += ";"
        if alias.const:
            values = ", ".join(_ts_value(v) for v in alias.node.values)
            head = f"export const {alias.const}: readonly {alias.name}[] = ["
            if len(head) + len(values) + 2 <= 110:
                lines.append(f"{head}{values}];")
            else:
                lines.append(head)
                lines.extend(f"  {_ts_value(v)}," for v in alias.node.values)
                lines.append("];")
        return lines

    def _ts_shape(self, name: str, spec: Spec) -> list[str]:
        lines = _ts_comment(spec.doc, "")
        fields = spec.fields if not spec.bases else spec.own
        body: list[str] = []
        for f in fields:
            body.extend(_ts_comment(f.doc, "  "))
            text, _ = self._ts(f.node)
            body.append(f"  {f.name}{'' if f.required else '?'}: {text};")
        if not spec.bases:
            if not body:
                return lines + [f"export type {name} = Record<string, never>;"]
            return lines + [f"export type {name} = {{"] + body + ["};"]
        base = " & ".join(spec.bases)
        if not body:
            return lines + [f"export type {name} = {base};"]
        return lines + [f"export type {name} = {base} & {{"] + body + ["};"]

    # --- checking a value ---

    def validate(self, value, name: str) -> list[str]:
        """The problems of `value` against the shape or alias `name`, each `"<path>: <what>"`; [] when it is valid."""
        if name in self.aliases:
            return self._check(self.aliases[name].node, value, "$")
        return self._check(Ref(name), value, "$")

    def _check(self, node, value, path: str) -> list[str]:
        if isinstance(node, AnyType):
            return []
        if isinstance(node, Prim):
            return [] if _is_prim(node.py, value) else [f"{path}: expected {node.py.__name__}, got {_kind(value)}"]
        if isinstance(node, Lit):
            ok = any(type(value) is type(v) and value == v for v in node.values)
            return [] if ok else [f"{path}: expected one of {list(node.values)!r}, got {value!r}"]
        if isinstance(node, Opt):
            return [] if value is None else self._check(node.inner, value, path)
        if isinstance(node, Many):
            if not isinstance(value, (list, tuple)):
                return [f"{path}: expected a list, got {_kind(value)}"]
            return [p for i, v in enumerate(value) for p in self._check(node.inner, v, f"{path}[{i}]")]
        if isinstance(node, Keyed):
            if not isinstance(value, dict):
                return [f"{path}: expected an object, got {_kind(value)}"]
            problems = []
            for key, v in value.items():
                if not isinstance(key, str):
                    problems.append(f"{path}: key {key!r} is not a string")
                else:
                    problems.extend(self._check(node.inner, v, f"{path}.{key}"))
            return problems
        if isinstance(node, Tup):
            if not isinstance(value, (list, tuple)):
                return [f"{path}: expected a list of {len(node.items)}, got {_kind(value)}"]
            if len(value) != len(node.items):
                return [f"{path}: expected {len(node.items)} items, got {len(value)}"]
            return [p for i, (n, v) in enumerate(zip(node.items, value)) for p in self._check(n, v, f"{path}[{i}]")]
        if isinstance(node, Either):
            first: list[str] = []
            for i, name in enumerate(node.names):
                problems = self._check(Ref(name), value, path)
                if not problems:
                    return []
                if i == 0:
                    first = problems
            return first
        if node.name in self.aliases:
            return self._check(self.aliases[node.name].node, value, path)
        return self._check_object(self._known(node.name), value, path)

    def _check_object(self, spec: Spec, value, path: str) -> list[str]:
        if not isinstance(value, dict):
            return [f"{path}: expected an object ({spec.cls.__name__}), got {_kind(value)}"]
        problems = []
        for f in spec.fields:
            if f.name not in value:
                if f.required:
                    problems.append(f"{path}.{f.name}: missing")
            else:
                problems.extend(self._check(f.node, value[f.name], f"{path}.{f.name}"))
        known = {f.name for f in spec.fields}
        problems.extend(f"{path}.{key}: unexpected key" for key in value if key not in known)
        return problems


def _is_prim(py: type, value) -> bool:
    if py is bool:
        return isinstance(value, bool)
    if isinstance(value, bool):
        return False
    return isinstance(value, (int, float)) if py is float else isinstance(value, py)


def _kind(value) -> str:
    return "null" if value is None else type(value).__name__


def _ts_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value) if isinstance(value, int) else _quote(value)


def _ts_comment(doc: str, indent: str) -> list[str]:
    """`/** doc */`, on one line when it fits, else a block."""
    if not doc:
        return []
    doc = doc.replace("*/", "* /")
    if len(indent) + len(doc) + 7 <= 112:
        return [f"{indent}/** {doc} */"]
    wrapped = textwrap.wrap(doc, width=108 - len(indent))
    return [f"{indent}/**"] + [f"{indent} * {line}" for line in wrapped] + [f"{indent} */"]


# --- the product's one registry ---

DEFAULT = Registry()
