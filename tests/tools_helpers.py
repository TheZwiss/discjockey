"""Fake yt-dlp folders for the tools tests, made of plain files: a built-in copy (a site-packages-like folder) and
update folders as unpacked wheels leave them. Never the network."""
from __future__ import annotations

import hashlib
import io
import json
import zipfile
from pathlib import Path
from types import SimpleNamespace

from discjockey import tools

YT_INIT = '''class YoutubeDL:
    def __init__(self, params=None):
        self.params = params or {}

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False
'''


def yt_dlp_files(version: str) -> dict[str, str]:
    """A yt_dlp package as small as --check-tools accepts: YoutubeDL, its version, one extractor."""
    return {
        "yt_dlp/__init__.py": YT_INIT,
        "yt_dlp/version.py": f"# Autogenerated by devscripts/update-version.py\n\n__version__ = '{version}'\n",
        "yt_dlp/extractor/__init__.py": "def gen_extractor_classes():\n    return [object]\n",
    }


def ejs_files(version: str) -> dict[str, str]:
    """A yt_dlp_ejs package laid out like the real one (version in _version.py, the solver's .js files)."""
    return {
        "yt_dlp_ejs/__init__.py": 'from yt_dlp_ejs._version import version\n\n__all__ = ["version"]\n',
        "yt_dlp_ejs/_version.py": f"__version__ = version = '{version}'\n",
        "yt_dlp_ejs/yt/__init__.py": "",
        "yt_dlp_ejs/yt/solver/__init__.py": "",
        "yt_dlp_ejs/yt/solver/core.min.js": "// solver\n",
    }


def write_files(folder: Path, files: dict[str, str]) -> None:
    for rel, text in files.items():
        p = folder / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")


def write_site(site: Path, yt: str = "2026.10.21") -> Path:
    """A folder like site-packages holding only yt_dlp: the built-in copy."""
    write_files(site, yt_dlp_files(yt))
    return site


def write_tools_folder(folder: Path, yt: str = "2026.10.28", ejs: str = "0.8.1") -> Path:
    """An update folder: yt_dlp and yt_dlp_ejs side by side."""
    write_files(folder, {**yt_dlp_files(yt), **ejs_files(ejs)})
    return folder


def install_update(support: Path, version: str, ejs: str = "0.8.1") -> Path:
    """<support>/tools/<version>/ with `current` pointing at it, as a finished update leaves it."""
    folder = write_tools_folder(tools.tools_root(support) / version, yt=version, ejs=ejs)
    link = tools.tools_root(support) / tools.CURRENT
    link.unlink(missing_ok=True)
    link.symlink_to(version)
    return folder.resolve()


def wheel(files: dict[str, str]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for name, text in files.items():
            z.writestr(name, text)
    return buf.getvalue()


def yt_wheel(version: str, ejs: str = "0.8.1") -> bytes:
    """yt-dlp's wheel: the package, its .dist-info, and data files an update must leave out."""
    return wheel({
        **yt_dlp_files(version),
        f"yt_dlp-{version}.dist-info/METADATA":
            f'Name: yt-dlp\nVersion: {version}\nRequires-Dist: yt-dlp-ejs=={ejs}; extra == "default"\n',
        f"yt_dlp-{version}.data/data/share/man/man1/yt-dlp.1": "man page\n",
    })


def ejs_wheel(version: str) -> bytes:
    return wheel({**ejs_files(version), f"yt_dlp_ejs-{version}.dist-info/METADATA":
                  f"Name: yt-dlp-ejs\nVersion: {version}\n"})


def _release(version: str, requires: list[str], filename: str, data: bytes) -> dict:
    return {"info": {"version": version, "requires_dist": requires},
            "urls": [{"packagetype": "sdist", "filename": f"pkg-{version}.tar.gz", "yanked": False,
                      "url": "https://files.example/sdist", "digests": {"sha256": "0" * 64}},
                     {"packagetype": "bdist_wheel", "filename": filename, "yanked": False,
                      "url": f"https://files.example/{filename}",
                      "digests": {"sha256": hashlib.sha256(data).hexdigest()}}]}


class FakePyPI:
    """PyPI's JSON API and files for one newest yt-dlp and the yt-dlp-ejs it pins. `damage="yt"` or `"ejs"`: that served wheel
    differs from PyPI's hash; `pin=False`: yt-dlp names no exact yt-dlp-ejs; `pure=False`: only a binary wheel.
    `requested`: every URL asked, in order."""

    def __init__(self, yt: str = "2026.10.28", ejs: str = "0.8.1", *, pin: bool = True, damage: str | None = None,
                 pure: bool = True):
        self.requested: list[str] = []
        yt_data, ejs_data = yt_wheel(yt, ejs), ejs_wheel(ejs)
        yt_name = f"yt_dlp-{yt}-py3-none-any.whl" if pure else f"yt_dlp-{yt}-cp312-cp312-macosx_11_0_arm64.whl"
        ejs_name = f"yt_dlp_ejs-{ejs}-py3-none-any.whl"
        self.files = {f"https://files.example/{yt_name}": yt_data + (b"x" if damage == "yt" else b""),
                      f"https://files.example/{ejs_name}": ejs_data + (b"x" if damage == "ejs" else b"")}
        requires = ['brotli; extra == "default"'] + ([f'yt-dlp-ejs=={ejs}; extra == "default"'] if pin else [])
        ejs_release = _release(ejs, [], ejs_name, ejs_data)
        self.json = {"https://pypi.org/pypi/yt-dlp/json": _release(yt, requires, yt_name, yt_data),
                     f"https://pypi.org/pypi/yt-dlp-ejs/{ejs}/json": ejs_release,
                     "https://pypi.org/pypi/yt-dlp-ejs/json": ejs_release}

    def __call__(self, url: str) -> bytes:
        self.requested.append(url)
        if url in self.json:
            return json.dumps(self.json[url]).encode()
        if url in self.files:
            return self.files[url]
        raise OSError(f"404 {url}")


class CheckRun:
    """Stands in for the --check-tools process (subprocess.run's signature): answers with the versions found in the
    folder it is given; ok=False: the check failed. `folders`: each folder it was asked about."""

    def __init__(self, ok: bool = True):
        self.ok, self.folders = ok, []

    def __call__(self, cmd, **kw):
        assert cmd[-2] == tools.CHECK_FLAG and kw.get("timeout")
        folder = Path(cmd[-1])
        self.folders.append(folder)
        if not self.ok:
            return SimpleNamespace(returncode=1, stdout="", stderr="ImportError: boom")
        out = {"yt-dlp": tools.package_version(folder / "yt_dlp"),
               "yt-dlp-ejs": tools.package_version(folder / "yt_dlp_ejs")}
        return SimpleNamespace(returncode=0, stdout="a warning first\n" + json.dumps(out) + "\n", stderr="")
